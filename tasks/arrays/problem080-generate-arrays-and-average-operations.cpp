/* 
Problem 080

Description:
Generates arrays based on intervals after -1 values,
copies segments whose sum equals 100, calculates averages
of odd values, and applies transformations on array halves.
*/

#include <iostream>
using namespace std;

// =========================================
// generate array
// =========================================
void generate(int X[], int size, int Y[], int ySize)
{
    int j = 0;
    int minVal = 999999;

    for(int i = 0; i < size; i++)
    {
        if(X[i] == -1)
        {
            int sum = 0;
            int start = i + 1;
            int end = start;

            while(end < size && X[end] != -1 && sum < 100)
            {
                sum += X[end];
                end++;
            }

            if(sum == 100)
            {
                for(int k = start; k < end; k++)
                {
                    Y[j] = X[k];

                    if(X[k] < minVal)
                    {
                        minVal = X[k];
                    }

                    j++;
                }
            }
        }
    }

    while(j < ySize)
    {
        Y[j] = minVal;
        j++;
    }
}

// =========================================
// average odd values
// =========================================
float avgOdd(int X[], int size)
{
    int sum = 0;
    int ct = 0;

    for(int i = 0; i < size; i++)
    {
        if(X[i] % 2 != 0)
        {
            sum += X[i];
            ct++;
        }
    }

    return (float)sum / ct;
}

// =========================================
// add value to first half
// =========================================
void addHalf(int X[], int size, float value)
{
    for(int i = 0; i < size / 2; i++)
    {
        X[i] += value;
    }
}

int main()
{
    int X[300];
    int Y[300];

    int Q[300];

    int W[500];

    int Z[400];

    int A[500];

    // =========================================
    // read X
    // =========================================
    for(int i = 0; i < 300; i++)
    {
        cin >> X[i];
    }

    // =========================================
    // Generate Y from X
    // =========================================
    generate(X, 300, Y, 300);

    // =========================================
    // averages
    // =========================================
    float a1 = avgOdd(Y, 300);
    float a2 = avgOdd(X, 300);

    // =========================================
    // add averages
    // =========================================
    addHalf(X, 300, a1);
    addHalf(Y, 300, a2);

    // =========================================
    // Generate Q from X
    // =========================================
    generate(X, 300, Q, 300);

    // =========================================
    // read W
    // =========================================
    for(int i = 0; i < 500; i++)
    {
        cin >> W[i];
    }

    // =========================================
    // Generate Q from W
    // =========================================
    generate(W, 500, Q, 300);

    // =========================================
    // averages
    // =========================================
    a1 = avgOdd(Q, 300);
    a2 = avgOdd(W, 500);

    // =========================================
    // add averages
    // =========================================
    addHalf(W, 500, a1);
    addHalf(Q, 300, a2);

    // =========================================
    // Generate Y from W
    // =========================================
    generate(W, 500, Y, 300);

    // =========================================
    // Generate X from W
    // =========================================
    generate(W, 500, X, 300);

    // =========================================
    // read new X
    // =========================================
    for(int i = 0; i < 300; i++)
    {
        cin >> X[i];
    }

    // =========================================
    // Generate Q from X
    // =========================================
    generate(X, 300, Q, 300);

    // =========================================
    // averages
    // =========================================
    a1 = avgOdd(Q, 300);
    a2 = avgOdd(X, 300);

    // =========================================
    // add averages
    // =========================================
    addHalf(X, 300, a1);
    addHalf(Q, 300, a2);

    // =========================================
    // Generate Y from X
    // =========================================
    generate(X, 300, Y, 300);

    // =========================================
    // averages
    // =========================================
    a1 = avgOdd(Y, 300);
    a2 = avgOdd(X, 300);

    // =========================================
    // Generate Q from X
    // =========================================
    generate(X, 300, Q, 300);

    // =========================================
    // read Z
    // =========================================
    for(int i = 0; i < 400; i++)
    {
        cin >> Z[i];
    }

    // =========================================
    // Generate Y from Z
    // =========================================
    generate(Z, 400, Y, 300);

    // =========================================
    // read A
    // =========================================
    for(int i = 0; i < 500; i++)
    {
        cin >> A[i];
    }

    // =========================================
    // Generate Q from A
    // =========================================
    generate(A, 500, Q, 300);

    // =========================================
    // print Q
    // =========================================
    for(int i = 0; i < 300; i++)
    {
        cout << Q[i] << " ";
    }

    return 0;
}