/* 
Problem 081

Description:
Finds the longest interval between -1 values,
copies it into another array, calculates averages,
and counts values smaller than these averages.
*/

#include <iostream>
using namespace std;

// =========================================
// generate array
// =========================================
void generate(int X[], int size, int Y[], int ySize)
{
    int maxLen = -999999;
    int maxStart;
    int maxEnd;

    // ===== search intervals =====
    for(int i = 0; i < size; i++)
    {
        if(X[i] == -1)
        {
            int start = i + 1;
            int end = start;

            // ===== search next -1 =====
            while(end < size && X[end] != -1)
            {
                end++;
            }

            int len = end - start;

            // ===== update longest =====
            if(len > maxLen)
            {
                maxLen = len;
                maxStart = start;
                maxEnd = end - 1;
            }

            i = end;
        }
    }

    // ===== fill Y with zeros =====
    for(int i = 0; i < ySize; i++)
    {
        Y[i] = 0;
    }

    // ===== copy longest interval at end =====
    int j = ySize - maxLen;

    for(int i = maxStart; i <= maxEnd; i++)
    {
        Y[j] = X[i];
        j++;
    }
}

// =========================================
// average array
// =========================================
float avg(int X[], int size)
{
    int sum = 0;

    for(int i = 0; i < size; i++)
    {
        sum += X[i];
    }

    return (float)sum / size;
}

// =========================================
// count values less than value
// =========================================
int countLess(int X[], int size, float value)
{
    int ct = 0;

    for(int i = size / 2; i < size; i++)
    {
        if(X[i] < value)
        {
            ct++;
        }
    }

    return ct;
}

